#!/usr/bin/env python3
"""Generate a bounded task-to-video index from formal LeRobot outputs."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

try:
    from .video_index import (
        DEFAULT_MAX_HIFI_EPISODES_PER_RECORD,
        DEFAULT_MAX_EPISODES_PER_RECORD,
        DEFAULT_MAX_LEROBOT_ROOTS,
        build_video_index,
        write_video_index,
    )
except ImportError:
    from video_index import (  # type: ignore[no-redef]
        DEFAULT_MAX_HIFI_EPISODES_PER_RECORD,
        DEFAULT_MAX_EPISODES_PER_RECORD,
        DEFAULT_MAX_LEROBOT_ROOTS,
        build_video_index,
        write_video_index,
    )


def build_argparser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalog", type=Path, required=True, help="catalog.json generated by build_catalog.py")
    parser.add_argument("--output", type=Path, required=True, help="Destination video-index.json")
    parser.add_argument("--conversion-pfs-root", type=Path, help="Formal LeRobot output root on PFS")
    parser.add_argument("--conversion-cfs-root", type=Path, help="Formal LeRobot output root on CFS")
    parser.add_argument("--max-episodes-per-record", type=int, default=DEFAULT_MAX_EPISODES_PER_RECORD)
    parser.add_argument(
        "--max-hifi-episodes-per-record",
        type=int,
        default=DEFAULT_MAX_HIFI_EPISODES_PER_RECORD,
        help="HiFi/Hy shared-video episode locators retained per task",
    )
    parser.add_argument("--max-lerobot-roots", type=int, default=DEFAULT_MAX_LEROBOT_ROOTS)
    return parser


def main() -> None:
    args = build_argparser().parse_args()
    catalog = json.loads(args.catalog.read_text(encoding="utf-8"))
    if not isinstance(catalog, dict):
        raise ValueError("catalog must contain a JSON object")
    index = build_video_index(
        catalog,
        pfs_root=args.conversion_pfs_root,
        cfs_root=args.conversion_cfs_root,
        max_episodes_per_record=args.max_episodes_per_record,
        max_hifi_episodes_per_record=args.max_hifi_episodes_per_record,
        max_lerobot_roots=args.max_lerobot_roots,
    )
    write_video_index(index, args.output)
    stats = index["stats"]
    print(
        f"wrote {args.output}: {stats['available_records']}/{stats['records']} records, "
        f"{stats['indexed_episodes']} episodes, {stats['indexed_videos']} videos"
    )


if __name__ == "__main__":
    main()
